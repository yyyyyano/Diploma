-- Находка T-007 (T-017): ключ часового пояса платформы совпадал с модулем system — теперь clock.time-zone.
-- Значение, заданное в админке до переименования, переносится под новый ключ (строки нет — нечего переносить).
UPDATE "settings" SET "key" = 'clock.time-zone' WHERE "key" = 'system.time-zone';
