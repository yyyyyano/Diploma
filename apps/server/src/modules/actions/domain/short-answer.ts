// Короткий ответ «да / нет» текстом (AGT-07, ARCHITECTURE §5): чат и бот распознают его кодом до запуска агента и
// отвечают на ожидающее решение той же функцией, что и кнопки. Только явные короткие ответы — «да, но в августе»
// уже вопрос агенту. Русский и белорусский (AGT-10); регистр, «ё», пробелы и знаки в конце не важны.

export type ShortAnswer = "yes" | "no";

const YES = new Set([
  "да",
  "ага",
  "угу",
  "конечно",
  "давай",
  "давайте",
  "подтверждаю",
  "верно",
  "ок",
  "окей",
  "хорошо",
  "так",
  "да, давай",
  "да, конечно",
  "да, подтверждаю",
]);

const NO = new Set([
  "нет",
  "не",
  "не надо",
  "не нужно",
  "отмена",
  "отменить",
  "неа",
  "не, не трэба",
  "не трэба",
]);

/** «да» → yes, «нет» → no; всё остальное — undefined (это вопрос агенту, а не ответ). */
export function parseShortAnswer(text: string): ShortAnswer | undefined {
  const plain = text
    .toLowerCase()
    .replaceAll("ё", "е")
    .trim()
    .replace(/[\s!.?…)]+$/u, "")
    .replace(/\s+/g, " ");
  if (YES.has(plain)) return "yes";
  if (NO.has(plain)) return "no";
  return undefined;
}
