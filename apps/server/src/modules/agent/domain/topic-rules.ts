// Стражи «вне темы» и защитный (AGT-12, SEC-10, P6): первая ступень — правила по словам, без модели. Дальше по
// ADR-0009 шли бы локальные эмбеддинги (bge-m3 не скачан — ступени пока нет) и малая модель `classify.off-topic`: её зовёт
// запуск агента только когда правила не уверены. Правила решают очевидное: финансовое — пропустить, явно постороннее —
// отказать, просьбу выбрать банк или вложить деньги — отказать (P6), приказ модели «забудь инструкции» — отказать.
export type RuleVerdict =
  /** Финансы, право о деньгах или работа с системой: пропустить к агенту. */
  | "on-topic"
  /** Явно постороннее: вежливый отказ с подсказкой, что ассистент умеет (AGT-12). */
  | "off-topic"
  /** Приказ модели забыть инструкции, раскрыть подсказку и т. п. (SEC-10): отказ без пересказа. */
  | "attack"
  /** Просьба посоветовать банк или продукт, куда вложить (P6): отказ без названий банков. */
  | "advice"
  /** Правила не уверены: решает малая модель. */
  | "unsure";

const plain = (text: string) => text.toLowerCase().replaceAll("ё", "е");

// Финансы, право о деньгах, работа с системой (основы слов, регистр и «ё» сняты).
const ON_TOPIC =
  /финанс|деньг|денежн|рубл|\bbyn\b|\busd\b|\beur\b|\brub\b|руб\b|коп\b|трат|потрат|расход|доход|зарплат|аванс|премия|операци|счет[аовеу]?\b|карт[аыуе]\b|баланс|остат|лимит|копилк|накоп|отлож|бюджет|кредит|займ|вклад|депозит|налог|вычет|ндфл|закон|стат(?:ья|ьи|ье|ью|ей)\b|кодекс|\bнк\b|пенси|пособи|штраф|договор|аренд|ипотек|чек[аиу]?\b|выписк|категори|кафе|такси|продукт|магазин|подписк|платеж|плат(?:ил|ить|у)\b|оплат|купил|покупк|удали|запиши|excel|эксель|отчет|календар|напомн|регулярн|ассистент|кошт|профил|курс валют|нбрб|гаранти|возврат|претензи|потребител|работодател|отпуск|больничн|алимент|наследств|страхов|осаго|квартир|жиль|коммунальн|жкх|инфляц|сбережен|патрац|выдатк|грош[ыаі]|рахун|падатк|заробак|плацеж|аплат|купіў|ліміт|картк|таксі|цифр[аы]? откуда|откуда цифр/u;

const OFF_TOPIC =
  /анекдот|стих[иов]*\b|песн[яюи]|рецепт|приготов|борщ|погод[аыу]|гороскоп|футбол|хоккей|чемпионат|фильм|сериал|игр[аыу] |видеоигр|python|javascript|typescript|напиши (?:код|программ|скрипт)|реферат|сочинени|курсовую|переведи (?:на|с) (?:английск|немецк|французск|испанск)|столиц[аыу]|кто такой|кто такая|расскажи (?:сказку|историю|про кошек)|шутк[уа]|любов[ьи]|отношени[яй] с (?:девушк|парн)/u;

/** «Какой банк лучше», «куда вложить»: конкретные банки и продукты не рекомендуем (P6, AGT-09). */
const ADVICE =
  /как(?:ой|ую|ие|ого) (?:банк|вклад|кредит|брокер|страхов)\p{L}* (?:лучше|выбрат|надежн|выгодн|порекоменду|посоветуй)|в как(?:ой|ом|ую) банк\p{L}*|(?:посоветуй|порекомендуй|подскажи|рекомендуешь)\p{L}* \p{L}*\s?(?:банк|вклад|кредит|брокер|акци|инвестиц|криптовалют|облигаци)|куда (?:лучше )?(?:вложить|инвестировать|положить деньги)|во что (?:лучше )?(?:вложить|инвестировать)|какие акции|какую криптовалют|стоит ли (?:покупать|инвестировать|вкладывать)/u;

// Реплика-продолжение: «а в августе?», «почему?», «покажи» — смысл от прежнего диалога.
const FOLLOW_UP_WORDS = 5;

export function ruleVerdict(input: {
  readonly text: string;
  /** В диалоге уже есть ответы ассистента: короткая реплика — продолжение. */
  readonly hasHistory: boolean;
  /** Фильтр шлюза llm нашёл в сообщении инструктивные фразы (SEC-10): считает запуск, здесь — только решение. */
  readonly injection: boolean;
}): RuleVerdict {
  if (input.injection) return "attack";
  const text = plain(input.text);
  if (ADVICE.test(text)) return "advice";
  if (ON_TOPIC.test(text) || /\d\s?(?:р\.|₽|\$|€)/u.test(text)) return "on-topic";
  if (OFF_TOPIC.test(text)) return "off-topic";
  const words = text.split(/\s+/u).filter((word) => word !== "");
  if (input.hasHistory && words.length <= FOLLOW_UP_WORDS) return "on-topic";
  return "unsure";
}
