// CAL-04, CAL-07, NFR-23: календарная арифметика событий — конец гарантии, момент напоминания по поясу системы, недели списка.
import { LocalDate } from "@kosht/kernel";
import { describe, expect, it } from "vitest";
import { addMonths, dueInstant, groupBounds, monthGrid, remindDate } from "./dates.ts";

const day = (iso: string) => LocalDate.parse(iso);

describe("CAL-04: конец гарантии — тот же день через N месяцев", () => {
  it("2 года (24 мес.) от 18.11.2024 — 18.11.2026", () => {
    expect(addMonths(day("2024-11-18"), 24)).toBe("2026-11-18");
  });

  it("покупка 31 января + 1 месяц — последний день февраля, а не март", () => {
    expect(addMonths(day("2026-01-31"), 1)).toBe("2026-02-28");
    expect(addMonths(day("2024-01-31"), 1)).toBe("2024-02-29");
  });

  it("29 февраля + 12 месяцев — 28 февраля следующего года", () => {
    expect(addMonths(day("2024-02-29"), 12)).toBe("2025-02-28");
  });

  it("через границу года: 15.11 + 3 мес. — 15.02", () => {
    expect(addMonths(day("2026-11-15"), 3)).toBe("2027-02-15");
  });
});

describe("CAL-07: когда напомнить", () => {
  it("за 7 дней до 1 декабря — 24 ноября; в день события — 1 декабря", () => {
    expect(remindDate(day("2026-12-01"), 7)).toBe("2026-11-24");
    expect(remindDate(day("2026-12-01"), 0)).toBe("2026-12-01");
  });

  it("за 5 дней до 5 марта — 28 февраля (високосный год — 29)", () => {
    expect(remindDate(day("2027-03-05"), 5)).toBe("2027-02-28");
    expect(remindDate(day("2028-03-05"), 5)).toBe("2028-02-29");
  });

  it("момент — время суток в поясе системы: 09:00 в Минске (UTC+3) — 06:00 UTC", () => {
    expect(dueInstant(day("2026-11-24"), "09:00", "Europe/Minsk").toISOString()).toBe(
      "2026-11-24T06:00:00.000Z",
    );
  });

  it("пояс с переходом на летнее время: Берлин, 09:00 зимой — 08:00 UTC, летом — 07:00 UTC", () => {
    expect(dueInstant(day("2026-01-15"), "09:00", "Europe/Berlin").toISOString()).toBe(
      "2026-01-15T08:00:00.000Z",
    );
    expect(dueInstant(day("2026-07-15"), "09:00", "Europe/Berlin").toISOString()).toBe(
      "2026-07-15T07:00:00.000Z",
    );
  });

  it("время суток не «чч:мм» — RangeError", () => {
    expect(() => dueInstant(day("2026-11-24"), "9:0", "Europe/Minsk")).toThrow(RangeError);
  });
});

describe("CAL-01: сетка месяца и группы списка", () => {
  it("октябрь 2026 (1 октября — четверг): сетка с 28 сентября по 1 ноября", () => {
    expect(monthGrid("2026-10")).toEqual({ from: "2026-09-28", to: "2026-11-01" });
  });

  it("февраль 2027 ровно в четыре недели: с 1 по 28 февраля (понедельник — воскресенье)", () => {
    expect(monthGrid("2027-02")).toEqual({ from: "2027-02-01", to: "2027-02-28" });
  });

  it("группы списка: эта неделя, следующая, месяцы до горизонта, «Позже»", () => {
    // 21.10.2026 — среда: эта неделя 19–25 октября, следующая 26 октября – 1 ноября.
    const groups = groupBounds(day("2026-10-21"), day("2027-01-19"));
    expect(groups.map((g) => [g.key, g.from, g.to])).toEqual([
      ["week-0", "2026-10-21", "2026-10-25"],
      ["week-1", "2026-10-26", "2026-11-01"],
      ["month-2026-11", "2026-11-02", "2026-11-30"],
      ["month-2026-12", "2026-12-01", "2026-12-31"],
      ["month-2027-01", "2027-01-01", "2027-01-19"],
      ["later", "2027-01-20", null],
    ]);
  });

  it("сегодня — воскресенье: «эта неделя» — один день, следующая — со следующего понедельника", () => {
    const groups = groupBounds(day("2026-10-25"), day("2026-11-15"));
    expect(groups.slice(0, 2).map((g) => [g.key, g.from, g.to])).toEqual([
      ["week-0", "2026-10-25", "2026-10-25"],
      ["week-1", "2026-10-26", "2026-11-01"],
    ]);
  });
});
