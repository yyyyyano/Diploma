/** Формы названия кодекса по падежам: «налоговый кодекс» → «налогового кодекса», «налоговому кодексу», «налоговом кодексе». */
function codeForms(adjective: string): string[] {
  return [
    `${adjective}ый кодекс`,
    `${adjective}ого кодекса`,
    `${adjective}ому кодексу`,
    `${adjective}ом кодексе`,
  ];
}

/** Формы названия закона: «о защите прав потребителей» → «закон о …», «закона о …», «закону о …», «законе о …». */
function lawForms(subject: string): string[] {
  return ["закон", "закона", "закону", "законе"].map((form) => `${form} о ${subject}`);
}

