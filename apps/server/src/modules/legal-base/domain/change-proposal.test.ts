// LAW-32: предложение модели принимается, только если статьи и дата дословно есть в тексте изменяющего акта; ID акта по реквизитам.
import { describe, expect, it } from "vitest";
import { pravoIdOf, verifyProposal } from "./change-proposal.ts";

const TEXT =
  "Статья 1. Внести в Налоговый кодекс изменения: статьи 209 и 210 изложить в новой редакции; дополнить статьёй 216¹. " +
  "Настоящий Закон вступает в силу 1 июля 2026 г.";

describe("LAW-32: проверка предложения модели по тексту", () => {
  it("статьи и дата, которые есть в тексте, принимаются", () => {
    expect(
      verifyProposal({ articles: ["209", "210", "216.1"], inForceOn: "2026-07-01" }, TEXT),
    ).toEqual({
      articles: ["209", "210", "216.1"],
      inForceOn: "2026-07-01",
    });
  });

  it("выдуманная статья и дата, которых в тексте нет, отбрасываются", () => {
    expect(verifyProposal({ articles: ["209", "999"], inForceOn: "2027-01-01" }, TEXT)).toEqual({
      articles: ["209"],
      inForceOn: null,
    });
  });

  it("дата в виде 01.07.2026 тоже находится", () => {
    expect(
      verifyProposal({ articles: [], inForceOn: "2026-07-01" }, "вступает в силу 01.07.2026"),
    ).toEqual({
      articles: [],
      inForceOn: "2026-07-01",
    });
  });
});

describe("LAW-11: ID изменяющего акта по реквизитам", () => {
  it.each([
    ["Закон Республики Беларусь от 16 марта 2026 г. № 134-З", "H12600134"],
    ["Постановление Совета Министров Республики Беларусь от 2 февраля 2022 г. № 62", "C22200062"],
    ["Указ Президента Республики Беларусь от 18 марта 2025 г. № 108", "P32500108"],
    ["Приказ Министерства финансов от 2 февраля 2022 г. № 5", null],
  ])("«%s» → %s", (description, id) => {
    expect(pravoIdOf(description)).toBe(id);
  });
});
