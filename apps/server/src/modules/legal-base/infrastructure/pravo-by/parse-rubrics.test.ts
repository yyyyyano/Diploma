// LAW-14: рубрики ЕПК. Страница `guid=11031` не сохранена с живого pravo.by (фикстуры — решение пользователя, T-034):
// вёрстка здесь — по описанию ресерча (код рубрики и название в отдельном элементе); проверка на живой странице — на первом
// запуске. Тест фиксирует, что разбор не зависит от классов и не принимает даты и номера за рубрики.
import { describe, expect, it } from "vitest";
import { parseRubrics } from "./parse-rubrics.ts";

describe("LAW-14: рубрики ЕПК карточки акта", () => {
  it("находит рубрики любой глубины и не повторяет их", () => {
    const html = `<html><body>
      <b>Рубрики ЕПК</b>
      <ul><li><a>04.01.14 Защита прав потребителей</a></li>
      <li>08.03 Пособия</li><li><span>08.03 Пособия</span></li></ul>
      <p>Принят 15.07.2008 Законом</p><div>Номер 2/1466</div></body></html>`;
    expect(parseRubrics(html)).toEqual(["04.01.14", "08.03"]);
  });

  it("страница без рубрик (переадресация на другую страницу) — пустой список", () => {
    expect(parseRubrics("<html><body><p>Национальный реестр</p></body></html>")).toEqual([]);
  });
});
