// PRIV-03: имена пользователя ловятся во всех падежах; чужие слова и суммы остаются.
import { describe, expect, it } from "vitest";
import { nameMatcher } from "./names.ts";

function found(names: string[], text: string): string[] {
  const match = nameMatcher(names);
  return match === undefined ? [] : match(text).map((span) => text.slice(span.start, span.end));
}

describe("PRIV-03: склонённый словарь имён", () => {
  it("имя и фамилия — во всех падежах, в любом регистре", () => {
    const text =
      "Сергей Иванов вернул долг. Передала Сергею, поговорила с Ивановым, письмо для СЕРГЕЯ ИВАНОВА, жена Ивановой";
    expect(found(["Сергей Иванов"], text)).toEqual([
      "Сергей",
      "Иванов",
      "Сергею",
      "Ивановым",
      "СЕРГЕЯ",
      "ИВАНОВА",
      "Ивановой",
    ]);
  });

  it("женские имена: Анна — Анны, Анне, Анну, Анной", () => {
    expect(found(["Анна"], "Анна, для Анны, с Анной, Анне, вижу Анну")).toEqual([
      "Анна",
      "Анны",
      "Анной",
      "Анне",
      "Анну",
    ]);
  });

  it("слово из словаря внутри другого слова не срабатывает", () => {
    expect(found(["Анна"], "Аннотация и аннулирование")).toEqual([]);
    expect(found(["Иван"], "Иванов вернул")).toEqual(["Иванов"]);
  });

  it("короткое имя — только как есть; инициалы и точки игнорируются", () => {
    expect(found(["Ян"], "Ян и Яна")).toEqual(["Ян"]);
    expect(found(["Иванов А.В."], "Иванов А. В. купил")).toEqual(["Иванов"]);
  });

  it("имён нет — матчера нет", () => {
    expect(nameMatcher([])).toBeUndefined();
    expect(nameMatcher(["  ", "."])).toBeUndefined();
  });

  it("суммы, даты и магазины не затрагиваются", () => {
    expect(found(["Сергей"], "Евроопт 21.10.2026 итого 8,47 BYN")).toEqual([]);
  });
});
