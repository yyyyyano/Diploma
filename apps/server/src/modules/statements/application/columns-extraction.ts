// Определение смысла колонок моделью (STMT-04 шаг 2, задача statement.columns): подсказка, строгая схема ответа и версия.
// Модель видит маленький замаскированный фрагмент и отвечает только «колонка N — роль»; строки разбирает код.
// Правка подсказки — новая версия (ключ кассет и eval).
import { z } from "zod";
import { ROLES } from "../domain/types.ts";

export const COLUMNS_PROMPT_VERSION = "statement-columns-v1";

export const ColumnMapping = z.strictObject({
  columns: z
    .array(
      z.strictObject({
        index: z.int().min(0).max(63),
        role: z.enum(ROLES),
      }),
    )
    .max(64),
});
export type ColumnMapping = z.infer<typeof ColumnMapping>;

