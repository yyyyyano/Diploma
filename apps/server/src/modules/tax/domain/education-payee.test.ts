// TAX-20: оплата обучения — категория «Образование» плюс признаки получателя (учреждение образования): словарь из настройки, без модели.
import { describe, expect, it } from "vitest";
import { DEFAULT_EDUCATION_PAYEE_WORDS, isEducationPayee } from "./education-payee.ts";

const words = DEFAULT_EDUCATION_PAYEE_WORDS;

describe("TAX-20: получатель — учреждение образования", () => {
  it.each([
    ["БГУ, оплата за обучение"],
    ["Белорусский государственный университет"],
    ["ИНСТИТУТ ПРЕДПРИНИМАТЕЛЬСТВА"],
    ["Минский государственный колледж электроники"],
    ["Академия управления при Президенте"],
  ])("«%s» — учреждение образования", (text) => {
    expect(isEducationPayee([text], words)).toBe(true);
  });

  it("признак ищется и в контрагенте, и в описании платежа", () => {
    expect(isEducationPayee([null, "Оплата за обучение, колледж, 2 семестр"], words)).toBe(true);
  });

  it("«ё» и «е» не различаются, регистр не важен", () => {
    expect(isEducationPayee(["Белорусский УНИВЕРСИТЕТ транспорта"], words)).toBe(true);
  });

  it.each([
    ["Автошкола «Старт»"],
    ["Репетитор по английскому"],
    ["Онлайн-курсы программирования"],
    [""],
  ])("«%s» — не учреждение образования: вычет не предлагаем", (text) => {
    expect(isEducationPayee([text], words)).toBe(false);
  });

  it("признак внутри слова не считается: «бгу» не находится в «ТЕХНОБГУМАГА»", () => {
    expect(isEducationPayee(["ТЕХНОБГУМАГА"], words)).toBe(false);
  });

  it("словарь пуст — ничего не находится", () => {
    expect(isEducationPayee(["БГУ"], [])).toBe(false);
  });
});
