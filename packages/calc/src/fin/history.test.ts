// FIN-20: «по данным за N мес.» — полные месяцы истории и окно расчёта.
import { describe, expect, it } from "vitest";
import { FREE_BALANCE_MONTHS, historyMonths, historyWindow, monthEnd } from "./history.ts";

describe("FIN-20: сколько месяцев истории", () => {
  it("первая операция в июле, сегодня 28.10 — три полных месяца (июль, август, сентябрь)", () => {
    expect(historyMonths("2026-07-15", "2026-10-28")).toBe(3);
  });
  it("история давнее трёх месяцев — всё равно три", () => {
    expect(historyMonths("2025-01-10", "2026-10-28")).toBe(FREE_BALANCE_MONTHS);
  });
  it("первая операция в августе — «по данным за 2 мес.»", () => {
    expect(historyMonths("2026-08-01", "2026-10-28")).toBe(2);
  });
  it("первая операция в этом месяце — полных месяцев нет, 0", () => {
    expect(historyMonths("2026-10-05", "2026-10-28")).toBe(0);
  });
  it("операций нет вовсе — 0", () => {
    expect(historyMonths(null, "2026-10-28")).toBe(0);
  });
  it("через границу года: первая операция в ноябре, сегодня 15.01 — два месяца", () => {
    expect(historyMonths("2025-11-20", "2026-01-15")).toBe(2);
  });
});

describe("FIN-20: окно расчёта", () => {
  it("три месяца до октября — с 1 июля по 30 сентября", () => {
    expect(historyWindow("2026-10-28", 3)).toEqual({ from: "2026-07-01", to: "2026-09-30" });
  });
  it("февраль високосного года: сегодня март, один месяц — 1…29 февраля", () => {
    expect(historyWindow("2028-03-10", 1)).toEqual({ from: "2028-02-01", to: "2028-02-29" });
  });
  it("через границу года: январь, два месяца — ноябрь и декабрь", () => {
    expect(historyWindow("2026-01-15", 2)).toEqual({ from: "2025-11-01", to: "2025-12-31" });
  });
});

describe("FIN-22: конец месяца", () => {
  it("октябрь — 31-е, февраль високосного — 29-е, апрель — 30-е", () => {
    expect(monthEnd("2026-10-28")).toBe("2026-10-31");
    expect(monthEnd("2028-02-10")).toBe("2028-02-29");
    expect(monthEnd("2026-04-01")).toBe("2026-04-30");
  });
});
